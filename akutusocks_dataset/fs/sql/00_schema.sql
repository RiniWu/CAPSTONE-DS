DROP VIEW IF EXISTS v_stok_ringkas;
DROP TABLE IF EXISTS log_inferensi, notifikasi, tindak_lanjut_selisih, selisih_stok, perbandingan_stok, detail_import, import_kasir,
  riwayat_validasi, item_laporan, riwayat_aktivitas, detail_stok_opname, stock_opname, detail_transaksi_stok, transaksi_stok,
  stok_barang, barang, token_aktivasi, pengguna, kategori_barang, gudang CASCADE;
DROP FUNCTION IF EXISTS tolak_ubah_riwayat();

CREATE TABLE gudang (
  id_gudang INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_gudang VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE kategori_barang (
  id_kategori INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kategori VARCHAR(100) NOT NULL UNIQUE, deskripsi VARCHAR(255), divisi VARCHAR(100));
CREATE TABLE pengguna (
  id_pengguna INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_lengkap VARCHAR(100) NOT NULL, email VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255),
  no_telepon VARCHAR(20) NOT NULL, alamat VARCHAR(255),
  status_akun VARCHAR(20) NOT NULL CHECK (status_akun IN ('belum_aktif','aktif','nonaktif')),
  role VARCHAR(10) NOT NULL CHECK (role IN ('owner','spv','staff')),
  wajib_ganti_password BOOLEAN NOT NULL DEFAULT FALSE,
  shift_kerja VARCHAR(30), nama_usaha VARCHAR(150), alamat_usaha VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ,
  CHECK (status_akun = 'belum_aktif' OR password_hash IS NOT NULL));
CREATE TABLE token_aktivasi (
  id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  token_hash VARCHAR(255) NOT NULL, kedaluwarsa_pada TIMESTAMPTZ NOT NULL, dipakai_pada TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE barang (
  kode_barang VARCHAR(20) PRIMARY KEY CHECK (kode_barang ~ '^[A-Za-z0-9-]+$'),
  nama_barang VARCHAR(80) NOT NULL,
  id_kategori INTEGER NOT NULL REFERENCES kategori_barang(id_kategori),
  harga_beli NUMERIC(15,2) NOT NULL, harga_jual NUMERIC(15,2) NOT NULL,
  minimum_stok INTEGER NOT NULL CHECK (minimum_stok >= 0),
  tipe_diskon SMALLINT NOT NULL DEFAULT 0 CHECK (tipe_diskon IN (0,1)),
  diskon NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (diskon >= 0),
  satuan VARCHAR(20) NOT NULL, berat_gram INTEGER, keterangan VARCHAR(255), gambar VARCHAR(255),
  sumber_data VARCHAR(50) NOT NULL DEFAULT 'sintetis',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ,
  CHECK (harga_beli < harga_jual));
CREATE TABLE stok_barang (
  id_stok INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_barang VARCHAR(20) NOT NULL REFERENCES barang(kode_barang),
  id_gudang INTEGER NOT NULL REFERENCES gudang(id_gudang),
  jumlah_stok INTEGER NOT NULL CHECK (jumlah_stok >= 0),
  letak_rak VARCHAR(30) NOT NULL, tanggal_pengecekan_terakhir DATE,
  UNIQUE (kode_barang, id_gudang));
CREATE TABLE transaksi_stok (
  id_transaksi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  jenis_transaksi VARCHAR(20) NOT NULL CHECK (jenis_transaksi IN ('masuk','keluar','pindah','penyesuaian')),
  waktu_transaksi TIMESTAMPTZ NOT NULL,
  status_transaksi VARCHAR(20) NOT NULL CHECK (status_transaksi IN ('Selesai','Dibatalkan')),
  alasan VARCHAR(255) NOT NULL, alasan_pembatalan VARCHAR(255),
  CHECK (status_transaksi <> 'Dibatalkan' OR alasan_pembatalan IS NOT NULL));
-- jumlah: positif untuk masuk/keluar/pindah; bertanda (+/-) untuk penyesuaian. masuk/penyesuaian memakai id_gudang_tujuan,
-- keluar memakai id_gudang_asal, pindah memakai keduanya.
CREATE TABLE detail_transaksi_stok (
  id_detail_transaksi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaksi INTEGER NOT NULL REFERENCES transaksi_stok(id_transaksi),
  kode_barang VARCHAR(20) NOT NULL REFERENCES barang(kode_barang),
  id_gudang_asal INTEGER REFERENCES gudang(id_gudang), id_gudang_tujuan INTEGER REFERENCES gudang(id_gudang),
  jumlah INTEGER NOT NULL CHECK (jumlah <> 0), stok_target INTEGER, no_batch VARCHAR(50), catatan VARCHAR(255),
  CHECK (id_gudang_asal IS NOT NULL OR id_gudang_tujuan IS NOT NULL));
CREATE TABLE stock_opname (
  id_opname INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_gudang INTEGER NOT NULL REFERENCES gudang(id_gudang), id_pengguna INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  waktu_opname TIMESTAMPTZ NOT NULL, status_opname VARCHAR(30) NOT NULL, catatan VARCHAR(255));
CREATE TABLE detail_stok_opname (
  id_detail_opname INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_opname INTEGER NOT NULL REFERENCES stock_opname(id_opname),
  kode_barang VARCHAR(20) NOT NULL REFERENCES barang(kode_barang),
  stok_sistem INTEGER NOT NULL CHECK (stok_sistem >= 0), stok_fisik INTEGER NOT NULL CHECK (stok_fisik >= 0),
  jumlah_selisih INTEGER NOT NULL, keterangan VARCHAR(255),
  UNIQUE (id_opname, kode_barang));
-- Riwayat bergaya commit. Untuk jenis 'stok_fisik': jumlah_sesudah = hasil hitung fisik, jumlah_perubahan = 0 (stok sistem tidak berubah).
CREATE TABLE riwayat_aktivitas (
  id_riwayat INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  id_transaksi INTEGER REFERENCES transaksi_stok(id_transaksi),
  id_detail_opname INTEGER REFERENCES detail_stok_opname(id_detail_opname),
  kode_barang VARCHAR(20) NOT NULL REFERENCES barang(kode_barang),
  id_gudang INTEGER NOT NULL REFERENCES gudang(id_gudang),
  jenis_aktivitas VARCHAR(20) NOT NULL CHECK (jenis_aktivitas IN ('masuk','keluar','pindah','penyesuaian','stok_fisik')),
  waktu_aktivitas TIMESTAMPTZ NOT NULL,
  jumlah_sebelum INTEGER NOT NULL, jumlah_sesudah INTEGER NOT NULL, jumlah_perubahan INTEGER NOT NULL,
  alasan VARCHAR(255) NOT NULL,
  id_riwayat_ref INTEGER REFERENCES riwayat_aktivitas(id_riwayat),
  CHECK (id_transaksi IS NOT NULL OR id_detail_opname IS NOT NULL));
CREATE INDEX idx_riwayat_barang_waktu ON riwayat_aktivitas (kode_barang, waktu_aktivitas);
CREATE INDEX idx_riwayat_gudang ON riwayat_aktivitas (id_gudang);
CREATE FUNCTION tolak_ubah_riwayat() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'riwayat_aktivitas bersifat hanya-baca (tidak boleh diubah atau dihapus)'; END; $$ LANGUAGE plpgsql;
CREATE TRIGGER trg_riwayat_hanya_baca BEFORE UPDATE OR DELETE ON riwayat_aktivitas
  FOR EACH ROW EXECUTE FUNCTION tolak_ubah_riwayat();
CREATE TABLE item_laporan (
  id_item_laporan INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_riwayat INTEGER NOT NULL UNIQUE REFERENCES riwayat_aktivitas(id_riwayat),
  status_item VARCHAR(20) NOT NULL CHECK (status_item IN ('Diajukan','Diterima','Ditolak')),
  diperiksa_oleh INTEGER REFERENCES pengguna(id_pengguna), diajukan_pada TIMESTAMPTZ NOT NULL);
CREATE INDEX idx_item_status ON item_laporan (status_item);
CREATE TABLE riwayat_validasi (
  id_riwayat_validasi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_item_laporan INTEGER NOT NULL REFERENCES item_laporan(id_item_laporan),
  id_spv INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  status_sebelumnya VARCHAR(20) NOT NULL, status_baru VARCHAR(20) NOT NULL,
  tanggal_validasi TIMESTAMPTZ NOT NULL, catatan_validasi VARCHAR(255),
  CHECK (status_baru <> 'Ditolak' OR catatan_validasi IS NOT NULL));
CREATE TABLE import_kasir (
  id_import INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_spv INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  nama_file VARCHAR(100) NOT NULL, format_file VARCHAR(50) NOT NULL, tanggal_import TIMESTAMPTZ NOT NULL, keterangan VARCHAR(255));
CREATE TABLE detail_import (
  id_detail_import INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_import INTEGER NOT NULL REFERENCES import_kasir(id_import),
  nomor_baris INTEGER NOT NULL, kode_barang_berkas VARCHAR(100) NOT NULL, nama_barang_berkas VARCHAR(255), jumlah_berkas INTEGER NOT NULL,
  status_pencocokan VARCHAR(30) NOT NULL CHECK (status_pencocokan IN ('sesuai','beda_jumlah','tidak_ditemukan')),
  alasan_gagal VARCHAR(100));
-- selisih = stok_pembanding (Kasir Pintar) - stok_website (total semua gudang). kode_barang NULL bila tidak ditemukan.
CREATE TABLE perbandingan_stok (
  id_perbandingan_stok INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_detail_import INTEGER NOT NULL REFERENCES detail_import(id_detail_import),
  kode_barang VARCHAR(20) REFERENCES barang(kode_barang),
  jenis_sumber VARCHAR(30) NOT NULL, stok_website INTEGER NOT NULL, stok_pembanding INTEGER NOT NULL, selisih INTEGER NOT NULL,
  status_perbandingan VARCHAR(30) NOT NULL CHECK (status_perbandingan IN ('sesuai','beda_jumlah','tidak_ditemukan')),
  tanggal_perbandingan TIMESTAMPTZ NOT NULL);
CREATE TABLE selisih_stok (
  id_selisih_stok INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_perbandingan_stok INTEGER REFERENCES perbandingan_stok(id_perbandingan_stok),
  id_detail_opname INTEGER REFERENCES detail_stok_opname(id_detail_opname),
  jenis_selisih VARCHAR(30) NOT NULL CHECK (jenis_selisih IN ('kurang_fisik','lebih_fisik','beda_jumlah','tidak_ditemukan')),
  status_kasus VARCHAR(30) NOT NULL CHECK (status_kasus IN ('Belum dicek','Sedang dicek ulang','Menunggu validasi','Selesai')),
  keterangan VARCHAR(255), created_at TIMESTAMPTZ NOT NULL,
  CHECK ((id_perbandingan_stok IS NOT NULL)::int + (id_detail_opname IS NOT NULL)::int = 1));
CREATE TABLE tindak_lanjut_selisih (
  id_tindak_lanjut INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_selisih_stok INTEGER NOT NULL REFERENCES selisih_stok(id_selisih_stok),
  id_pengguna INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  jenis_tindakan VARCHAR(30) NOT NULL CHECK (jenis_tindakan IN ('hitung_ulang','isi_hasil_fisik','validasi','penyesuaian_stok','koreksi_kasir')),
  tanggal_tindak_lanjut TIMESTAMPTZ NOT NULL, catatan VARCHAR(255));
CREATE TABLE notifikasi (
  id_notifikasi INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INTEGER NOT NULL REFERENCES pengguna(id_pengguna),
  jenis VARCHAR(20) NOT NULL CHECK (jenis IN ('penolakan','selisih_baru','pengingat')),
  judul VARCHAR(100) NOT NULL, isi_pesan TEXT NOT NULL, dibaca BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL);
CREATE TABLE log_inferensi (
  id_log INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INTEGER REFERENCES pengguna(id_pengguna), pertanyaan TEXT NOT NULL, intent VARCHAR(50), skor NUMERIC(5,4), jawaban TEXT,
  status VARCHAR(20) NOT NULL CHECK (status IN ('berhasil','ditolak','gagal')), waktu TIMESTAMPTZ NOT NULL DEFAULT now());
-- Status stok dihitung (tidak disimpan): habis / rendah (< minimum_stok total semua gudang) / aman.
CREATE VIEW v_stok_ringkas AS
SELECT b.kode_barang, b.nama_barang, b.minimum_stok, COALESCE(SUM(s.jumlah_stok),0) AS total_stok,
  CASE WHEN COALESCE(SUM(s.jumlah_stok),0) = 0 THEN 'habis'
       WHEN COALESCE(SUM(s.jumlah_stok),0) < b.minimum_stok THEN 'rendah' ELSE 'aman' END AS status_stok
FROM barang b LEFT JOIN stok_barang s ON s.kode_barang = b.kode_barang
GROUP BY b.kode_barang, b.nama_barang, b.minimum_stok;
